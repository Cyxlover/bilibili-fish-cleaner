#!/usr/bin/env node
// 把 engine/ 的 ESM 源码拼成内容脚本可用的 IIFE。
//
// 内容脚本是经典脚本，不能 import ESM；这里只用 Node 内置能力做确定性拼接：
// 依赖按拓扑顺序排列，去掉单行 import 与 export 前缀，最后包一层 IIFE，
// 同时挂到 window.__FISH_ENGINE__ 与 DSHCC.engine。
//
// 用法：
//   node scripts/build-engine.mjs          # 重新生成
//   node scripts/build-engine.mjs --check  # 只检查是否漂移（CI/测试用）

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = new URL('../', import.meta.url);
const OUTPUT = fileURLToPath(new URL('src/lib/engine-bundle.js', ROOT));

// 依赖在前，入口在最后；新增文件时同步维护这里。
const FILES = [
  'engine/catalog.js',
  'engine/observation.js',
  'engine/longform.js',
  'engine/profile.js',
  // 资料按需读取：profile-need 只决定「要不要读」，profile-reader 负责「怎么读」，
  // 两者都进 bundle 是因为内容脚本与 Service Worker 都要用同一份判定与读取纪律。
  'engine/profile-need.js',
  'engine/profile-reader.js',
  'engine/rules.js',
  'engine/index.js',
];

function transform(source, file) {
  const lines = source.split(/\r?\n/);
  const output = [];
  for (const line of lines) {
    if (/^import\s/.test(line)) continue;
    if (/^export\s*\{[^}]*\}\s*;?\s*$/.test(line)) continue;
    output.push(line.replace(/^export\s+(const|function|class|let|var)\s+/, '$1 '));
  }
  return `// ---- ${file} ----\n${output.join('\n').trim()}\n`;
}

function build() {
  const body = FILES.map((file) => {
    const source = readFileSync(new URL(file, ROOT), 'utf8');
    return transform(source, file);
  }).join('\n');

  return `// AUTO-GENERATED by scripts/build-engine.mjs — 不要手改，改 engine/ 后重新生成。
(function (global) {
  'use strict';
  var NS = (global.DSHCC = global.DSHCC || {});

${body}
  var api = Object.freeze({
    ACTIONS: ACTIONS,
    DEFAULT_RULES_VERSION: DEFAULT_RULES_VERSION,
    RULE_VERSIONS: RULE_VERSIONS,
    // 资料按需读取对两侧都开放：内容脚本用 needsProfile 判断缺口，
    // Service Worker 用 createProfileReader 真正去取（内容脚本不发请求）。
    needsProfile: needsProfile,
    createProfileCache: createProfileCache,
    createProfileReader: createProfileReader,
    judge: judge,
    listRules: listRules,
    resolveRule: resolveRule
  });
  NS.engine = api;
  global.__FISH_ENGINE__ = api;
})(typeof globalThis !== 'undefined' ? globalThis : window);
`;
}

const next = build();
const check = process.argv.includes('--check');
const current = (() => {
  try {
    return readFileSync(OUTPUT, 'utf8');
  } catch (error) {
    return null;
  }
})();

if (check) {
  if (current !== next) {
    console.error('engine-bundle.js 已漂移，请运行 node scripts/build-engine.mjs');
    process.exitCode = 1;
  } else {
    console.log('engine-bundle.js 与 engine/ 一致');
  }
} else if (current === next) {
  console.log('engine-bundle.js 无变化');
} else {
  writeFileSync(OUTPUT, next, 'utf8');
  console.log('已生成 src/lib/engine-bundle.js');
}
